// Regenerates the skills index from SKILL.md frontmatter. Idempotent: only writes on change.
// Usage: node scripts/build-skills-index.mjs [--skills-dir .ai/skills] [--out .ai/skills-index.md] [--quiet]
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const argv = process.argv.slice(2);
const opt = (name, def) => {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : def;
};
const skillsDir = opt("--skills-dir", ".ai/skills");
const out = opt("--out", ".ai/skills-index.md");
const quiet = argv.includes("--quiet");

function frontmatter(text) {
  const m = text.replace(/\r\n/g, "\n").match(/^---\n([\s\S]*?)\n---/);
  const fm = {};
  if (!m) return fm;
  const lines = m[1].split("\n");
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (!kv) continue;
    let val = kv[2].trim();
    if (/^[>|][+-]?$/.test(val)) {
      const parts = [];
      while (i + 1 < lines.length && /^\s+\S/.test(lines[i + 1])) parts.push(lines[++i].trim());
      val = parts.join(" ");
    }
    fm[kv[1]] = val.replace(/^["']|["']$/g, "");
  }
  return fm;
}

const oneLine = (s, max = 160) => {
  const t = s.replace(/\s+/g, " ").trim();
  return t.length > max ? t.slice(0, max - 1) + "…" : t;
};

const rows = [];
if (existsSync(skillsDir)) {
  for (const d of readdirSync(skillsDir, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name.startsWith("_") || d.name.startsWith(".")) continue;
    const file = join(skillsDir, d.name, "SKILL.md");
    if (!existsSync(file)) continue;
    const fm = frontmatter(readFileSync(file, "utf8"));
    rows.push({ name: fm.name || d.name, desc: oneLine(fm.description || "(no description)"), path: `${skillsDir}/${d.name}/SKILL.md` });
  }
}
rows.sort((a, b) => a.name.localeCompare(b.name));

const body = [
  "# Skills index",
  "",
  "<!-- Generated by scripts/build-skills-index.mjs — do not hand-edit. Refreshed on session start and on file writes. -->",
  "<!-- Open a skill's SKILL.md only when the task matches its description. -->",
  "",
  ...(rows.length
    ? ["| Skill | Use when | File |", "|---|---|---|", ...rows.map((r) => `| ${r.name} | ${r.desc.replace(/\|/g, "\\|")} | ${r.path} |`)]
    : ["_No skills installed._"]),
  "",
].join("\n");

const prev = existsSync(out) ? readFileSync(out, "utf8") : null;
if (prev !== body) {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body);
  if (!quiet) console.log(`skills index updated: ${rows.length} skill(s) -> ${out}`);
} else if (!quiet) {
  console.log(`skills index unchanged: ${rows.length} skill(s)`);
}
